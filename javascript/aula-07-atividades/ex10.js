function celsiusParaFahrenheit(c){
    return (c * 9/5) + 32.
}
let temperatura =  celsiusParaFahrenheit(0)
let temperatura1 =  celsiusParaFahrenheit(100)
console.log(`a temperatura de celsius para fahrenheit é ${temperatura}°F`)
console.log(`a temperatura de celsius para fahrenheit é ${temperatura1}°F`)
